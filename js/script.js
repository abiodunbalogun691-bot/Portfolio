/* =========================================
   3. LANGUAGE SWITCHING
========================================= */

function setLanguage(language) {
    if (!translations[language]) {
        language = "en";
    }

    const dictionary = translations[language];

    // Update page language and browser tab title.
    document.documentElement.lang = language;
    document.title = dictionary.pageTitle;

    // Translate the text of mapped elements.
    Object.entries(translationMap).forEach(([selector, key]) => {
        const element = document.querySelector(selector);

        if (!element) {
            return;
        }

        // Preserve the highlighted name and final word
        // in the section titles.
        if (selector === ".hero h1") {
            const name = document.createElement("span");
            name.textContent = "Abiodun Sarah Balogun";

            element.replaceChildren(
                document.createTextNode(dictionary.greeting + " "),
                name
            );

        } else if (
            selector === ".about .section-title" ||
            selector === ".skills .section-title" ||
            selector === ".projects .section-title" ||
            selector === ".experience .section-title"
        ) {
            const span = element.querySelector("span");

            if (span) {
                const originalHighlightedText = span.textContent;

                element.replaceChildren(
                    document.createTextNode(dictionary[key] + " "),
                    span
                );

                // Translate the highlighted word separately.
                const highlightedWords = {
                    about: { en: "Me", fr: "moi" },
                    skills: { en: "Skills", fr: "compétences" },
                    projects: { en: "Projects", fr: "à la une" },
                    experience: {
                        en: "Leadership",
                        fr: "leadership"
                    }
                };

                const titleType = selector.includes("about")
                    ? "about"
                    : selector.includes("skills")
                    ? "skills"
                    : selector.includes("projects")
                    ? "projects"
                    : "experience";

                span.textContent =
                    highlightedWords[titleType][language];

            } else {
                element.textContent = dictionary[key];
            }

        } else {
            element.textContent = dictionary[key];
        }
    });

    // Update the mobile menu's accessible label.
    const menuToggle = document.getElementById("menu-toggle");

    if (menuToggle) {
        const isOpen = menuToggle.getAttribute("aria-expanded") === "true";

        menuToggle.setAttribute(
            "aria-label",
            isOpen ? dictionary.menuClose : dictionary.menuOpen
        );
    }

    // Update language button appearance and accessibility.
    document.querySelectorAll(".language-btn").forEach(button => {
        const isActive = button.dataset.lang === language;

        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    // Remember the visitor's language.
    try {
        localStorage.setItem("portfolioLanguage", language);
    } catch (error) {
        console.warn("Language preference could not be saved.");
    }
}


/* =========================================
   4. LANGUAGE BUTTON EVENTS
========================================= */

document.querySelectorAll(".language-btn").forEach(button => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.lang);
    });
});


/* =========================================
   5. MOBILE NAVIGATION
========================================= */

const menuToggle = document.getElementById("menu-toggle");
const navLinks = document.getElementById("nav-links");

if (menuToggle && navLinks) {
    menuToggle.addEventListener("click", () => {
        const isOpen = navLinks.classList.toggle("open");

        menuToggle.setAttribute("aria-expanded", String(isOpen));
        menuToggle.textContent = isOpen ? "✕" : "☰";

        const language =
            document.documentElement.lang || "en";

        menuToggle.setAttribute(
            "aria-label",
            isOpen
                ? translations[language].menuClose
                : translations[language].menuOpen
        );
    });

    // Close the menu after a navigation link is selected.
    navLinks.querySelectorAll("a").forEach(link => {
        link.addEventListener("click", () => {
            navLinks.classList.remove("open");
            menuToggle.setAttribute("aria-expanded", "false");
            menuToggle.textContent = "☰";

            const language =
                document.documentElement.lang || "en";

            menuToggle.setAttribute(
                "aria-label",
                translations[language].menuOpen
            );
        });
    });
}


